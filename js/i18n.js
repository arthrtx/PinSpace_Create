    function tr(text) {
        if (lang !== 'en' || !text) return text;
        const lead = text.match(/^\s*/)[0], trail = text.match(/\s*$/)[0];
        const core = text.trim().replace(/\s+/g, ' ');
        if (!core) return text;
        if (Object.prototype.hasOwnProperty.call(DICT, core)) return lead + DICT[core] + trail;
        for (const [re, fn] of PATTERNS) {
            const m = core.match(re);
            if (m) {
                const out = fn(...m);
                if (out != null) return lead + out + trail;
            }
        }
        // mensagens com várias linhas (confirm/alert)
        if (core !== text.trim() && /\n/.test(text)) {
            const parts = text.split(/\n/).map((l) => tr(l));
            return parts.join('\n');
        }
        return text;
    }

    /* ---------- DOM ---------- */
    const ATTRS = ['placeholder', 'title', 'aria-label', 'alt'];
    const SKIP = '#board-elements, [contenteditable="true"], script, style, .no-i18n';
    const NOTEXT = 'textarea, select'; // só os atributos (o texto é do utilizador)
    const ORIG = new WeakMap(); // nó de texto → texto original (pt)
    const DONE = new WeakMap(); // nó de texto → último texto escrito por nós
    const AORIG = new WeakMap(); // elemento → { atributo: original }

    const skipped = (el) => !el || (el.closest && el.closest(SKIP));

    function doText(node) {
        const cur = node.nodeValue;
        if (DONE.get(node) !== cur) ORIG.set(node, cur); // texto novo vindo da app
        const orig = ORIG.get(node);
        if (orig == null) return;
        const want = lang === 'en' ? tr(orig) : orig;
        if (want !== cur) { node.nodeValue = want; }
        DONE.set(node, want);
    }

    function doAttrs(el) {
        let o = AORIG.get(el);
        for (const a of ATTRS) {
            if (!el.hasAttribute(a)) continue;
            const v = el.getAttribute(a);
            if (!o) { o = {}; AORIG.set(el, o); }
            if (o['_' + a] !== v) o[a] = v; // valor novo vindo da app
            const want = lang === 'en' ? tr(o[a]) : o[a];
            if (want !== v) el.setAttribute(a, want);
            o['_' + a] = want;
        }
    }

    function walk(root) {
        if (!root) return;
        if (root.nodeType === 3) { const pe = root.parentElement; if (!skipped(pe) && !(pe && pe.closest(NOTEXT))) doText(root); return; }
        if (root.nodeType !== 1 && root.nodeType !== 11) return;
        if (root.nodeType === 1) { if (skipped(root)) return; doAttrs(root); }
        const w = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT, {
            acceptNode: (n) => {
                if (n.nodeType !== 1) return NodeFilter.FILTER_ACCEPT;
                if (n.matches(SKIP)) return NodeFilter.FILTER_REJECT;
                if (n.matches(NOTEXT)) { doAttrs(n); return NodeFilter.FILTER_REJECT; }
                return NodeFilter.FILTER_ACCEPT;
            }
        });
        let n;
        while ((n = w.nextNode())) {
            if (n.nodeType === 3) { if (/[A-Za-zÀ-ÿ]/.test(n.nodeValue)) doText(n); }
            else doAttrs(n);
        }
    }

    let busy = false;
    const mo = new MutationObserver((list) => {
        if (busy) return;
        busy = true;
        try {
            for (const m of list) {
                if (m.type === 'childList') m.addedNodes.forEach(walk);
                else if (m.type === 'characterData') { const pe = m.target.parentElement; if (!skipped(pe) && !(pe && pe.closest(NOTEXT))) doText(m.target); }
                else if (m.type === 'attributes') { if (!skipped(m.target)) doAttrs(m.target); }
            }
        } finally { busy = false; mo.takeRecords(); }
    });

    function apply() {
        busy = true;
        try {
            walk(document.body);
            document.documentElement.lang = lang === 'en' ? 'en' : 'pt-PT';
            document.querySelectorAll('.ps-lang-toggle').forEach((b) => {
                b.textContent = lang === 'en' ? 'PT' : 'EN';
                b.setAttribute('aria-label', lang === 'en' ? 'Ver o site em português' : 'View the site in English');
                b.title = b.getAttribute('aria-label');
                AORIG.delete(b);
            });
        } finally { busy = false; mo.takeRecords(); }
    }

    function setLang(l) {
        lang = l === 'pt' ? 'pt' : 'en';
        try { localStorage.setItem(KEY, lang); } catch { /* ok */ }
        apply();
        window.dispatchEvent(new CustomEvent('pinspace:lang', { detail: lang }));
    }

    /* ---------- Botão ao lado de "pin space." ---------- */
    function addToggles() {
        document.querySelectorAll('.ms-nav > .ms-nav-brand').forEach((brand) => {
            if (brand.parentElement.querySelector('.ps-lang-toggle')) return;
            const wrap = document.createElement('div');
            wrap.className = 'ps-brand-group';
            brand.parentNode.insertBefore(wrap, brand);
            wrap.appendChild(brand);
            const b = document.createElement('button');
            b.type = 'button';
            b.className = 'ps-lang-toggle no-i18n';
            b.addEventListener('click', (e) => { e.preventDefault(); e.stopPropagation(); setLang(lang === 'en' ? 'pt' : 'en'); });
            wrap.appendChild(b);
        });
    }

    /* ---------- Diálogos do navegador ---------- */
    const _confirm = window.confirm.bind(window);
    const _alert = window.alert.bind(window);
    const _prompt = window.prompt.bind(window);
    window.confirm = (m) => _confirm(tr(String(m ?? '')));
    window.alert = (m) => _alert(tr(String(m ?? '')));
    window.prompt = (m, d) => _prompt(tr(String(m ?? '')), d);

    /* ---------- API pública ---------- */
    window.psLang = () => lang;
    window.psLocale = () => (lang === 'en' ? 'en-GB' : 'pt-PT');
    window.psT = tr;
    window.psSetLang = setLang;

    function start() {
        addToggles();
        apply();
        mo.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS });
    }
    if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start);
    else start();
